def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _canonical_json_bytes(value: Any) -> bytes:
    try:
        return json.dumps(
            value,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
            allow_nan=False,
        ).encode("utf-8")
    except (TypeError, ValueError) as error:
        raise ConfigurationError(f"value is not canonical JSON: {error}") from error


def _canonical_sha256(value: Any) -> str:
    return hashlib.sha256(_canonical_json_bytes(value)).hexdigest()


def _require_string(value: Any, name: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ConfigurationError(f"{name} must be a non-empty string")
    return value.strip()


def _require_sha256(value: Any, name: str) -> str:
    digest = _require_string(value, name).lower()
    if len(digest) != 64 or any(char not in "0123456789abcdef" for char in digest):
        raise ConfigurationError(f"{name} must be a SHA-256 digest")
    return digest


def _require_revision(value: Any, name: str) -> str:
    revision = _require_string(value, name).lower()
    if len(revision) != 40 or any(char not in "0123456789abcdef" for char in revision):
        raise ConfigurationError(f"{name} must be a 40-character commit revision")
    return revision


def _require_exact_keys(
    data: Mapping[str, Any], expected: set[str], *, name: str
) -> None:
    observed = set(data)
    if observed != expected:
        missing = sorted(expected - observed)
        unexpected = sorted(observed - expected)
        raise ConfigurationError(
            f"{name} keys mismatch: missing={missing}, unexpected={unexpected}"
        )


def _json_object_copy(value: Mapping[str, Any], name: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise ConfigurationError(f"{name} must be a JSON object")
    decoded = json.loads(_canonical_json_bytes(dict(value)).decode("utf-8"))
    if not isinstance(decoded, dict):
        raise ConfigurationError(f"{name} must serialize to a JSON object")
    return MappingProxyType(decoded)


def _dtype_name(dtype: torch.dtype) -> str:
    names = {
        torch.float32: "float32",
        torch.bfloat16: "bfloat16",
    }
    try:
        return names[dtype]
    except KeyError as error:
        raise ConfigurationError(
            f"unsupported Draft parameter dtype: {dtype}"
        ) from error


def _torch_dtype(name: str) -> torch.dtype:
    names = {"float32": torch.float32, "bfloat16": torch.bfloat16}
    try:
        return names[name]
    except KeyError as error:
        raise ConfigurationError(
            "draft_parameter_dtype must be 'float32' or 'bfloat16'"
        ) from error


