"""Derive and authenticate a RoboTwin pi0.5 Draft from a pi0 warm start.

The published Realtime-VLA FLASH heads are seven-dimensional LIBERO/pi0
artifacts.  This module deliberately provides no conversion that can bless
those bytes for direct pi0.5 inference.  A published head may enter only the
warm-start function below.  That function copies the state token, H=50 query
tokens, and Gemma decoder block, while a new 32-dimensional output layer is
initialized from scratch.

Production authorization is a separate, content-addressed chain:

* training exports an immutable *candidate* safetensors file and manifest;
* an evaluation report binds that exact manifest;
* an Ed25519 approval signs the candidate, target, weights, and evaluation;
* the production loader re-verifies every hash, tensor key/shape/dtype, target
  semantic field, and signature before returning an inference-only adapter.

No metric or experiment result is generated by this module.  All metrics in
an artifact are supplied by the completed training/evaluation process.
"""

